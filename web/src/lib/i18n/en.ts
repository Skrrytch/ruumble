const plural = (n: number, one: string, many: string) => (n === 1 ? one : many);
const MUMBLE_OFFLINE = "Mumble is not connected.";
const ordinal = (n: number) => {
  const s = n % 100 >= 11 && n % 100 <= 13 ? "th" : ({ 1: "st", 2: "nd", 3: "rd" } as Record<number, string>)[n % 10] ?? "th";
  return `${n}${s}`;
};

/** "after one year", "after 30 days", "right away" (house rules of the care dialogs) */
const after = (days: number) =>
  days === 0 ? "right away" : days % 365 === 0 ? (days === 365 ? "after one year" : `after ${days / 365} years`) : days === 1 ? "after one day" : `after ${days} days`;

